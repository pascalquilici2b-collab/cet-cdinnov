import type {Database,Reply} from './contracts';
import {applyRecordChanges,validateChanges,type RecordPath} from './record-changes';
import {readRecordSource,saveRecordSource} from './record-writes';
import {jsonBody,validateWorkspace,validateState} from '../server/legacy-runtime.mjs';
const emptyBudget={demo:false,clients:[],projects:[],budgetLines:[],expenses:[],drs:[],imports:[]};
const emptySheets={version:1,sampleData:false,profile:{name:'Équipe',organization:'CD Innovation'},workspaces:[],sheets:[],dashboards:[],activity:[]};
function brokenBudgetLinks(doc:Record<string,any>){
  const broken=new Set<string>();
  for(const [collection,field,target] of [['projects','clientId','clients'],['budgetLines','projectId','projects'],['expenses','projectId','projects'],['expenses','budgetLineId','budgetLines'],['drs','projectId','projects'],['imports','projectId','projects'],['partnerReports','projectId','projects']]){
    const ids=new Set((doc[target]||[]).map((r:any)=>r.id));
    for(const r of doc[collection]||[])if(r[field]&&!ids.has(r[field]))broken.add(JSON.stringify([collection,r.id,field,r[field]]));
  }
  return broken;
}
// These are display timestamps regenerated by ordinary sheet edits. They must not
// turn edits of two unrelated rows into a conflict on their parent sheet.
export const sheetTimestamp=(p:RecordPath)=>p[0]==='sheets'&&typeof p[1]==='object'&&(p.length===3&&p[2]==='updatedAt'||p.length===5&&p[2]==='rows'&&typeof p[3]==='object'&&p[4]==='updatedAt');
export async function workspaceRecords(request:Request,db:Database,domain:'budgets'|'sheets',email:string,reply:Reply){
  const body=await jsonBody(request,4000000);validateChanges(body.changes);
  for(let attempt=0;attempt<6;attempt++){
    const current=await readRecordSource(db,domain,domain==='budgets'?emptyBudget:emptySheets,domain==='budgets'?0:1);
    const next=applyRecordChanges(current.document,body.changes,domain==='sheets'?sheetTimestamp:undefined);
    if(domain==='budgets'){
      if(!validateWorkspace(next))return reply(400,{error:'Structure des budgets invalide.'});
      const previous=brokenBudgetLinks(current.document);
      if([...brokenBudgetLinks(next)].some(link=>!previous.has(link)))return reply(409,{error:'Un client, projet ou poste lié a changé. Votre copie est conservée : rechargez avant de reporter cette modification.'});
    }else{
      try{validateState(next);}catch(error){return reply(400,{error:error instanceof Error?error.message:'Structure Smartsheet invalide.'});}
    }
    const saved=await saveRecordSource(db,domain,current.document,next,current.version,email,current.exists);
    if(saved!==null)return reply(200,domain==='budgets'?{saved:true,version:saved}:{ok:true,revision:saved});
  }
  return reply(409,{error:'Plusieurs enregistrements sont en cours. Votre copie est conservée. Réessayez.'});
}
