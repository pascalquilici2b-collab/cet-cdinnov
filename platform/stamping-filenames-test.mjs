import assert from 'node:assert/strict';
import {stampedDocumentNames,stampedLotFilename} from './stamping-filenames.ts';
const doc=(id,name,employee,period)=>({id,name,data:{reading:{fields:{document_type:'PAYSLIP',employee_name:employee,period}}}});
const first=doc('1','paie.pdf','Véronique SCIARETTI','2024-09');
assert.equal(stampedDocumentNames([first]).get('1'),'DR_EPCIC_RH_Véronique_SCIARETTI_Septembre_2024.pdf');
const second=doc('2','paie.pdf','Nicole SPINOSI','2025-02');
const names=stampedDocumentNames([first,second]);
assert.equal(names.get('1'),'Véronique SCIARETTI/DR_EPCIC_RH_Véronique_SCIARETTI_Septembre_2024.pdf');
assert.equal(names.get('2'),'Nicole SPINOSI/DR_EPCIC_RH_Nicole_SPINOSI_Février_2025.pdf');
const duplicate=stampedDocumentNames([first,{...first,id:'copy'}]);
assert.equal(duplicate.get('copy'),'DR_EPCIC_RH_Véronique_SCIARETTI_Septembre_2024_02.pdf');
const confirmed={...first,data:{groupId:'g',reading:{fields:{document_type:'PAYSLIP',employee_ref:'AGENT001',period:'2025-03'}}}};
assert.equal(stampedDocumentNames([confirmed],[{id:'g',employee_ref:'Marie MARTIN',period:'2025-02',document_type:'PAYSLIP'}]).get('1'),'DR_EPCIC_RH_Marie_MARTIN_Février_2025.pdf');
const services={id:'invoice',name:'Facture fournisseur.pdf',data:{reading:{fields:{document_type:'INVOICE'}}}};
assert.equal(stampedDocumentNames([services]).get('invoice'),'Facture fournisseur_tamponné.pdf');
const dangerous=stampedDocumentNames([doc('x','ignored','../../Agent: test','2024-99')]).get('x');
assert.ok(!dangerous.includes('/')&&!dangerous.includes('\\')&&!dangerous.includes(':'));
assert.ok(dangerous.includes('Mois_non_identifié'));
assert.equal(stampedLotFilename('RH / Octobre'),'RH - Octobre tamponné.zip');
console.log('Payroll names, French months, per-agent folders, confirmed groups, duplicate protection and safe paths passed.');
